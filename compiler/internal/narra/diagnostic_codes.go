var codeByFormat = func() map[string]string {
	m := make(map[string]string, len(diagnosticCodes))
	for _, d := range diagnosticCodes {
		if _, dup := m[d.Format]; dup {
			panic("duplicate diagnostic format: " + d.Format)
		}
		m[d.Format] = d.Code
	}
	return m
}()

// codeFor returns the code of a message format, or E0000 when it has none.
func codeFor(format string) string {
	if c, ok := codeByFormat[format]; ok {
		return c
	}
	return "E0000"
}

