#!/bin/sh
# Print docs/reference/errors.md, made from `narrac explain --list --json`.
#   NARRAC=/path/to/narrac sh scripts/error-index.sh > docs/reference/errors.md
# NARRAC defaults to narrac on the PATH. The codes suite of selfhost/tests fails when the
# committed page differs from this output; `sh scripts/test.sh --suite generated --update`
# rewrites it. jq must be installed.
set -eu

narrac=${NARRAC:-narrac}
if ! command -v jq >/dev/null 2>&1; then
  echo "error-index.sh: jq is not installed" >&2
  exit 2
fi

"$narrac" explain --list --json | jq -r '
  def area: {
    "00": "Lexer and parser",
    "01": "Declarations and types",
    "02": "Expressions and statements",
    "03": "Calls and constructors",
    "04": "Modules, packages and narra.toml",
    "05": "Traits",
    "06": "Closures and function values",
    "07": "Patterns and match",
    "08": "Effects",
    "09": "Standard library",
    "10": "C interop and unsafe code",
    "11": "Concurrency",
    "12": "Types and parameters: templates, defaults, refinements, effect lists, SIMD, ranges",
    "13": "Standard library modules for tools",
    "14": "Channels, Shared and Atomic",
    "15": "Unreachable statements and unused let",
    "16": "Build targets"
  }[.[1:3]];
  def render:
    "### \(.code)\n\n```text\n\(.messages | join("\n"))\n```\n"
    + (if .explanation == null then "" else "\n\(.explanation | split("\n") | join("\n\n"))\n" end);
  "# Errors\n\nEvery diagnostic code of `narrac`, with its message and, where there is one, its explanation. `narrac explain CODE` prints the same text. In a message, `%s`, `%q`, `%d`, `%c` and `%v` mark a name, text, number or character that the compiler fills in. A code with several messages is reported in several situations.\n"
  + "\nThis page is generated by `scripts/error-index.sh` from `narrac explain --list --json`. Do not edit it.\n"
  + (group_by(.code[1:3]) | map(
      "\n## E\(.[0].code[1:3])00 to E\(.[0].code[1:3])99: \(.[0].code | area)\n\n"
      + (map(render) | join("\n"))
    ) | join(""))
'
