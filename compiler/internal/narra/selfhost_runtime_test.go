package narra

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"testing"
)

// runtimeTextPath is the generated Narra module with the C runtime texts.
const runtimeTextPath = "../../../selfhost/src/runtimetext.nra"

// narraString writes text as a Narra string literal. The runtime texts are
// ASCII; a `$` is escaped so no `${` starts an interpolation.
func narraString(t *testing.T, text string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(text); i++ {
		c := text[i]
		switch {
		case c == '\\' || c == '"' || c == '$':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '\n':
			b.WriteString("\\n")
		case c == '\t':
			b.WriteString("\\t")
		case c == '\r':
			b.WriteString("\\r")
		case c >= 0x20 && c < 0x7f:
			b.WriteByte(c)
		default:
			t.Fatalf("runtime text has a byte 0x%02x that the generator does not escape", c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// runtimeConstName names the constant that holds the runtime of a std module.
func runtimeConstName(path string) string {
	return "RUNTIME_" + strings.ToUpper(strings.ReplaceAll(path, "/", "_"))
}

// runtimeTextSource builds runtimetext.nra from Go's own runtime strings.
func runtimeTextSource(t *testing.T) string {
	var b strings.Builder
	b.WriteString("// Generated by TestSelfhostRuntimeText from the C runtime texts of the Go\n")
	b.WriteString("// compiler. Do not edit: NARRA_UPDATE=1 go test -run TestSelfhostRuntimeText rewrites it.\n\n")
	consts := []struct{ name, text string }{
		{"RUNTIME_H", runtimeH},
		{"RUNTIME_MAP_H", runtimeMapH},
		{"ENV_RUNTIME", envRuntime},
		{"TEST_RUNNER_C", testRunnerC},
	}
	var paths []string
	for path, m := range stdModules {
		if m.Runtime != "" {
			paths = append(paths, path)
		}
	}
	sort.Strings(paths)
	for _, c := range consts {
		fmt.Fprintf(&b, "export const %s = %s\n\n", c.name, narraString(t, c.text))
	}
	for _, path := range paths {
		fmt.Fprintf(&b, "const %s = %s\n\n", runtimeConstName(path), narraString(t, stdModules[path].Runtime))
	}
	b.WriteString("// runtimeFor is the C runtime of a std module, or \"\" when it has none.\n")
	b.WriteString("export function runtimeFor(path: string): string {\n")
	for _, path := range paths {
		fmt.Fprintf(&b, "  if (path == %q) {\n    return %s\n  }\n", path, runtimeConstName(path))
	}
	b.WriteString("  return \"\"\n}\n")
	return b.String()
}

// TestSelfhostRuntimeText fails when runtimetext.nra differs from the Go
// runtime strings. NARRA_UPDATE=1 rewrites the file.
func TestSelfhostRuntimeText(t *testing.T) {
	want := runtimeTextSource(t)
	if os.Getenv("NARRA_UPDATE") != "" {
		if err := os.WriteFile(runtimeTextPath, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(runtimeTextPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatalf("runtimetext.nra is stale (NARRA_UPDATE=1 rewrites it): %s", firstDiff(want, string(got)))
	}
}
